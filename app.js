// A single gentle reveal per section; content stays visible without JavaScript.
function setupMotion(){
  if(!('IntersectionObserver' in window)||window.matchMedia('(prefers-reduced-motion: reduce)').matches)return;
  const observer=new IntersectionObserver(entries=>{
    for(const entry of entries)if(entry.isIntersecting){entry.target.classList.add('is-visible');observer.unobserve(entry.target);}
  },{threshold:0.06,rootMargin:'0px 0px -20px 0px'});
  document.querySelectorAll('.work-card,.lab,.case-section,.history-row,.recognition article').forEach(el=>{
    const rect=el.getBoundingClientRect();
    if(rect.top<window.innerHeight-20&&rect.bottom>0)return;
    el.classList.add('motion-pending');observer.observe(el);
  });
}
setupMotion();
